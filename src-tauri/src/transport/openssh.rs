    /// End-to-end check with a real `ssh` and two local sshd instances
    /// (hop on SSHTERM_E2E_HOP_PORT, target on SSHTERM_E2E_TARGET_PORT, both on
    /// 127.0.0.1, key auth for SSHTERM_E2E_USER via the default identity).
    /// Starts from an empty known_hosts and forces askpass (which answers
    /// nothing), exactly the situation in which `-J` + `-o` failed with
    /// "Host key verification failed" on the first hop.
    #[test]
    #[ignore = "needs ssh and two local sshd instances; see the env vars above"]
    fn real_ssh_completes_a_jump_chain_with_a_fresh_known_hosts() {
        let (Ok(hop), Ok(target), Ok(user)) = (
            std::env::var("SSHTERM_E2E_HOP_PORT"),
            std::env::var("SSHTERM_E2E_TARGET_PORT"),
            std::env::var("SSHTERM_E2E_USER"),
        ) else {
            panic!("set SSHTERM_E2E_HOP_PORT, SSHTERM_E2E_TARGET_PORT and SSHTERM_E2E_USER");
        };
        let dir = tempfile::tempdir().unwrap();
        let mut config = cfg();
        config.program = PathBuf::from("ssh");
        config.host = "127.0.0.1".into();
        config.port = target.parse().unwrap();
        config.user = user.clone();
        config.known_hosts = dir.path().join("known_hosts");
        config.jump_hosts = vec![super::super::JumpHost {
            user,
            host: "127.0.0.1".into(),
            port: hop.parse().unwrap(),
        }];
        let conf_path = write_jump_config(&config).unwrap();
        let mut args = argv(&build_command(&config, None, Some(&conf_path)));
        args.remove(0); // program
        args.push("echo SSHTERM_E2E_OK".into());
        let askpass = dir.path().join("askpass.sh");
        std::fs::write(&askpass, "#!/bin/sh\necho \"\"\n").unwrap();
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            std::fs::set_permissions(&askpass, std::fs::Permissions::from_mode(0o755)).unwrap();
        }
        let out = std::process::Command::new("ssh")
            .args(&args)
            .env("SSH_ASKPASS", &askpass)
            .env("SSH_ASKPASS_REQUIRE", "force")
            .env("DISPLAY", "sshterm")
            .output()
            .unwrap();
        let _ = std::fs::remove_file(&conf_path);
        let text = String::from_utf8_lossy(&out.stdout).to_string() + &String::from_utf8_lossy(&out.stderr);
        assert!(text.contains("SSHTERM_E2E_OK"), "ssh output: {text}");
        let kh = std::fs::read_to_string(&config.known_hosts).unwrap();
        assert_eq!(kh.lines().count(), 2, "both hop and target keys land in OUR known_hosts: {kh}");
    }

    /// Manual diagnostic for the ConPTY -> reader thread path. Ignored by
    /// default: CreatePseudoConsole needs an attached interactive console, and
    /// a headless `cargo test` process does not drive the child at all.
    #[cfg(windows)]
    #[test]
    #[ignore = "requires an attached interactive console"]
    fn conpty_forwards_child_output() {
        use portable_pty::PtySize as RawSize;
        use std::io::Read;
        use std::time::Duration;

        let pty = native_pty_system();
        let pair = pty
            .openpty(RawSize { rows: 24, cols: 80, pixel_width: 0, pixel_height: 0 })
            .unwrap();
        let marker = std::env::temp_dir().join(format!("sshterm-pty-{}.txt", std::process::id()));
        let marker_arg = format!("echo MARKER > {} & echo SSHtermConPtyOk", marker.display());
        let mut cmd = CommandBuilder::new("cmd.exe");
        cmd.arg("/c");
        cmd.arg(marker_arg);
        let mut child = pair.slave.spawn_command(cmd).unwrap();
        // Some ConPTY builds need an explicit resize before they flush output.
        let _ = pair.master.resize(RawSize {
            rows: 24,
            cols: 80,
            pixel_width: 0,
            pixel_height: 0,
        });
        let mut reader = pair.master.try_clone_reader().unwrap();

        let (tx, rx) = std::sync::mpsc::channel();
        std::thread::spawn(move || {
            let mut buf = [0u8; 4096];
            let mut all = Vec::new();
            for _ in 0..8 {
                match reader.read(&mut buf) {
                    Ok(0) | Err(_) => break,
                    Ok(n) => {
                        all.extend_from_slice(&buf[..n]);
                        if all.contains(&b'\n') && all.len() > 20 {
                            break;
                        }
                    }
                }
            }
            let _ = tx.send(all);
        });

        let got = rx.recv_timeout(Duration::from_secs(10));
        let ran = marker.exists();
        let status = child.try_wait();
        eprintln!("child ran (marker file) = {ran}, status = {status:?}");
        if ran {
            let _ = std::fs::remove_file(&marker);
        }
        let bytes = got.unwrap_or_else(|_| {
            panic!("no PTY output (child ran = {ran}, status = {status:?})")
        });
        let text = String::from_utf8_lossy(&bytes);
        eprintln!("ConPTY output: {text:?}");
        assert!(text.contains("SSHtermConPtyOk"), "PTY output was not forwarded");
        let _ = child.kill();
    }
