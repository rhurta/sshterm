//! Phase 1 engine: Windows `ssh.exe` run inside a ConPTY.
//!
//! The application owns the terminal: PTY bytes are forwarded to the frontend
//! as `session:data` events, and the frontend sends input via `session_write`.
//! Resizing uses `MasterPty::resize`.

use std::io::{Read, Write};
use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::{Arc, Mutex};
use std::time::Duration;

use async_trait::async_trait;
use portable_pty::{
    native_pty_system, Child, CommandBuilder, MasterPty, PtySize as RawPtySize,
};

use super::{OutputReceiver, PtySize, SshConfig, Transport, TransportError};
use crate::askpass::{AskpassServer, PIPE_ENV, TOKEN_ENV};

type SharedMaster = Arc<Mutex<Option<Box<dyn MasterPty + Send>>>>;
type SharedChild = Arc<Mutex<Option<Box<dyn Child + Send + Sync>>>>;

pub struct OpenSshTransport {
    askpass: Option<AskpassServer>,
    master: SharedMaster,
    writer: Option<Box<dyn Write + Send>>,
    child: SharedChild,
    stop: Arc<AtomicBool>,
    output: Option<OutputReceiver>,
}

impl OpenSshTransport {
    pub fn new(askpass: Option<AskpassServer>) -> Self {
        Self {
            askpass,
            master: Arc::new(Mutex::new(None)),
            writer: None,
            child: Arc::new(Mutex::new(None)),
            stop: Arc::new(AtomicBool::new(false)),
            output: None,
        }
    }

    /// Synchronous helper: keeps the std MutexGuard out of the async future
    /// generated by async_trait (a std guard is not Send).
    fn do_resize(&self, size: PtySize) -> Result<(), TransportError> {
        let guard = self
            .master
            .lock()
            .map_err(|_| TransportError::new("pty_resize", "master lock poisoned"))?;
        // A resize arriving after ssh exited is harmless; the watchdog has
        // already dropped the master by then.
        let Some(master) = guard.as_ref() else { return Ok(()) };
        master
            .resize(raw_size(size))
            .map_err(|e| TransportError::new("pty_resize", e.to_string()))
    }

    fn kill_child(&mut self) {
        self.stop.store(true, Ordering::Relaxed);
        self.writer = None;
        if let Ok(mut guard) = self.child.lock() {
            if let Some(mut child) = guard.take() {
                let _ = child.kill();
            }
        }
    }
}

fn raw_size(size: PtySize) -> RawPtySize {
    RawPtySize {
        rows: size.rows,
        cols: size.cols,
        pixel_width: 0,
        pixel_height: 0,
    }
}

/// Builds the command line without executing anything: this way `cargo test`
/// can verify the flags are correct without an SSH server.
fn build_command(cfg: &SshConfig, askpass: Option<(&str, &str)>) -> CommandBuilder {
    let mut cmd = CommandBuilder::new(&cfg.program);
    // -tt forces an interactive remote terminal; without it ssh does not
    // allocate a TTY when it detects its local input is not a real console.
    cmd.arg("-tt");
    cmd.arg("-p");
    cmd.arg(cfg.port.to_string());
    cmd.arg("-o");
    cmd.arg(format!("UserKnownHostsFile={}", cfg.known_hosts.display()));
    cmd.arg("-o");
    // SSH_ASKPASS_REQUIRE=force makes ssh route *every* prompt through the
    // askpass helper, including the host-key "yes/no" question. The helper can
    // only answer with a password, so ssh reads that as "no" and aborts with
    // "Host key verification failed." without ever showing the question in the
    // terminal. accept-new implements TOFU instead: ssh adds a first-seen key
    // to our own known_hosts file (and prints a warning), while a changed key
    // is still rejected with the loud "REMOTE HOST IDENTIFICATION HAS CHANGED"
    // banner. Command-line -o wins over any ~/.ssh/config the user may have.
    cmd.arg("StrictHostKeyChecking=accept-new");
    cmd.arg("-o");
    cmd.arg(format!("ServerAliveInterval={}", cfg.keepalive_secs));
    cmd.arg("-o");
    cmd.arg("ServerAliveCountMax=3");
    cmd.arg("-o");
    // A stalled TCP connect must not leave the terminal blank forever.
    cmd.arg("ConnectTimeout=15");
    if let Some(key) = &cfg.key_path {
        cmd.arg("-i");
        cmd.arg(key.display().to_string());
    }
    if !cfg.jump_hosts.is_empty() {
        cmd.arg("-J");
        cmd.arg(
            cfg.jump_hosts
                .iter()
                .map(|hop| hop.proxy_spec())
                .collect::<Vec<_>>()
                .join(","),
        );
    }
    if !cfg.forwards.is_empty() {
        // Ask ssh.exe to fail instead of leaving a session open with a silently
        // missing local or remote listener (for example, when a port is busy).
        cmd.arg("-o");
        cmd.arg("ExitOnForwardFailure=yes");
        for forward in &cfg.forwards {
            cmd.arg(forward.option());
            cmd.arg(forward.argument());
        }
    }
    cmd.arg(format!("{}@{}", cfg.user, cfg.host));

    if let Some((pipe, token)) = askpass {
        // OpenSSH builds the command "<askpass> <prompt>" without quoting,
        // so the path is quoted here to work with spaces.
        let helper = format!("\"{}\"", cfg.askpass_program.display());
        cmd.env("SSH_ASKPASS", helper);
        cmd.env("SSH_ASKPASS_REQUIRE", "force");
        cmd.env("DISPLAY", "sshterm");
        cmd.env(PIPE_ENV, pipe);
        cmd.env(TOKEN_ENV, token);
    }
    cmd
}

#[async_trait]
impl Transport for OpenSshTransport {
    async fn open(&mut self, cfg: &SshConfig, size: PtySize) -> Result<(), TransportError> {
        let pty = native_pty_system();
        let pair = pty
            .openpty(raw_size(size))
            .map_err(|e| TransportError::new("pty_open", e.to_string()))?;

        let askpass_env = self
            .askpass
            .as_ref()
            .map(|a| (a.pipe_name(), a.token()));
        let cmd = build_command(cfg, askpass_env);

        let child = pair
            .slave
            .spawn_command(cmd)
            .map_err(|e| TransportError::new("ssh_spawn", e.to_string()))?;
        let reader = pair
            .master
            .try_clone_reader()
            .map_err(|e| TransportError::new("pty_reader", e.to_string()))?;
        let writer = pair
            .master
            .take_writer()
            .map_err(|e| TransportError::new("pty_writer", e.to_string()))?;

        // portable-pty is blocking: a dedicated thread avoids occupying the
        // Tauri runtime. The UnboundedSender drops when the PTY reaches EOF.
        let (tx, rx) = tokio::sync::mpsc::unbounded_channel::<Vec<u8>>();
        // Clone before the reader thread takes ownership of `tx`.
        let watch_tx = tx.clone();
        let reader_thread = std::thread::Builder::new()
            .name(format!("sshterm-pty-{}", cfg.host))
            .spawn(move || {
                let mut reader = reader;
                let mut buf = [0u8; 8192];
                loop {
                    match reader.read(&mut buf) {
                        Ok(0) | Err(_) => break,
                        Ok(n) => {
                            if tx.send(buf[..n].to_vec()).is_err() {
                                break;
                            }
                        }
                    }
                }
            })
            .map_err(|e| TransportError::new("pty_thread", e.to_string()))?;

        if let Ok(mut guard) = self.master.lock() {
            *guard = Some(pair.master);
        }
        if let Ok(mut guard) = self.child.lock() {
            *guard = Some(child);
        }
        self.writer = Some(writer);

        // ConPTY does not reliably deliver EOF on its output pipe when ssh.exe
        // exits, so the reader thread can stay blocked and `session:closed`
        // never fires (the tab just hangs). This watchdog polls the child; on
        // exit it drops the PTY master (which lets the reader unblock) and
        // pushes an empty chunk as an explicit EOF sentinel.
        let watch_child = Arc::clone(&self.child);
        let watch_master = Arc::clone(&self.master);
        let watch_stop = Arc::clone(&self.stop);
        std::thread::Builder::new()
            .name(format!("sshterm-watch-{}", cfg.host))
            .spawn(move || {
                loop {
                    if watch_stop.load(Ordering::Relaxed) {
                        break;
                    }
                    let exited = match watch_child.lock() {
                        Ok(mut guard) => match guard.as_mut() {
                            Some(c) => matches!(c.try_wait(), Ok(Some(_))),
                            None => true,
                        },
                        Err(_) => true,
                    };
                    if exited {
                        break;
                    }
                    std::thread::sleep(Duration::from_millis(100));
                }
                // Give ConPTY a moment to flush the last output (the "logout" line, an
                // error message) before the PTY is closed. When the session is being
                // closed on purpose there is nothing left to wait for.
                if !watch_stop.swap(true, Ordering::Relaxed) {
                    std::thread::sleep(Duration::from_millis(150));
                }
                if let Ok(mut guard) = watch_master.lock() {
                    let _ = guard.take(); // unblocks the reader thread
                }
                // The end marker must come AFTER everything the reader still has to
                // send; otherwise the receiver stops at the marker and loses the tail.
                // Wait for the reader, but never hang the session if ConPTY does not
                // release it: after 2 seconds the end marker is sent anyway.
                for _ in 0..40 {
                    if reader_thread.is_finished() {
                        let _ = reader_thread.join();
                        break;
                    }
                    std::thread::sleep(Duration::from_millis(50));
                }
                let _ = watch_tx.send(Vec::new());
            })
            .map_err(|e| TransportError::new("pty_watch", e.to_string()))?;

        self.output = Some(rx);
        Ok(())
    }

    async fn write(&mut self, data: &[u8]) -> Result<(), TransportError> {
        let writer = self
            .writer
            .as_mut()
            .ok_or_else(|| TransportError::new("session_closed", "no pty writer"))?;
        writer
            .write_all(data)
            .map_err(|e| TransportError::new("pty_write", e.to_string()))?;
        writer
            .flush()
            .map_err(|e| TransportError::new("pty_write", e.to_string()))?;
        Ok(())
    }

    async fn resize(&mut self, size: PtySize) -> Result<(), TransportError> {
        self.do_resize(size)
    }

    async fn close(&mut self) -> Result<(), TransportError> {
        self.kill_child();
        if let Ok(mut guard) = self.master.lock() {
            let _ = guard.take();
        }
        self.askpass = None; // stops the pipe server
        Ok(())
    }

    fn output(&mut self) -> Option<OutputReceiver> {
        self.output.take()
    }
}

impl Drop for OpenSshTransport {
    fn drop(&mut self) {
        // Ensures no orphan ssh.exe processes remain when closing the app or
        // the session.
        self.kill_child();
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::PathBuf;

    fn cfg() -> SshConfig {
        SshConfig {
            program: PathBuf::from("ssh.exe"),
            askpass_program: PathBuf::from("sshterm.exe"),
            known_hosts: PathBuf::from("known_hosts"),
            host: "10.0.0.5".into(),
            port: 2222,
            user: "admin".into(),
            keepalive_secs: 45,
            key_path: None,
            jump_hosts: Vec::new(),
            forwards: Vec::new(),
        }
    }

    fn argv(cmd: &CommandBuilder) -> Vec<String> {
        cmd.get_argv()
            .iter()
            .map(|s| s.to_string_lossy().into_owned())
            .collect()
    }

    #[test]
    fn ssh_flags_match_the_spec() {
        let args = argv(&build_command(&cfg(), None));
        assert_eq!(args[0], "ssh.exe");
        assert!(args.contains(&"-tt".to_string()));
        assert!(args.windows(2).any(|w| w[0] == "-p" && w[1] == "2222"));
        assert!(args.contains(&"UserKnownHostsFile=known_hosts".to_string()));
        assert!(args.contains(&"StrictHostKeyChecking=accept-new".to_string()));
        assert!(args.contains(&"ServerAliveInterval=45".to_string()));
        assert!(args.contains(&"ServerAliveCountMax=3".to_string()));
        assert!(args.contains(&"ConnectTimeout=15".to_string()));
        assert_eq!(args.last().map(String::as_str), Some("admin@10.0.0.5"));
    }

    /// Regression: with forced askpass, ssh hands the host-key yes/no question
    /// to the helper, which answers with a password and ssh aborts with
    /// "Host key verification failed." The policy must be in place even when
    /// askpass is active.
    #[test]
    fn host_key_policy_survives_forced_askpass() {
        let args = argv(&build_command(&cfg(), Some(("pipe", "token"))));
        assert!(args.contains(&"StrictHostKeyChecking=accept-new".to_string()));
        assert!(args.windows(2).any(|w| w[0] == "-o" && w[1] == "StrictHostKeyChecking=accept-new"));
    }

    #[test]
    fn no_password_never_leaks_into_the_command_line() {
        let args = argv(&build_command(&cfg(), Some(("pipe", "token"))));
        assert!(!args.iter().any(|a| a.contains("token") || a.contains("pipe")));
        assert_eq!(args.last().map(String::as_str), Some("admin@10.0.0.5"));
    }

    #[test]
    fn key_auth_adds_the_identity_file_flag() {
        let mut config = cfg();
        config.key_path = Some(PathBuf::from("C:/keys/id_ed25519"));
        let args = argv(&build_command(&config, None));
        assert!(args.windows(2).any(|w| w[0] == "-i" && w[1] == "C:/keys/id_ed25519"));
        assert_eq!(args.last().map(String::as_str), Some("admin@10.0.0.5"));
    }

    #[test]
    fn jump_chain_is_passed_to_openssh_in_order() {
        let mut config = cfg();
        config.jump_hosts = vec![
            super::super::JumpHost {
                user: "bastion".into(),
                host: "gateway.example".into(),
                port: 2201,
            },
            super::super::JumpHost {
                user: "relay".into(),
                host: "10.0.0.8".into(),
                port: 22,
            },
        ];
        let args = argv(&build_command(&config, None));
        let jump = args.windows(2).find(|w| w[0] == "-J").unwrap();
        assert_eq!(jump[1], "bastion@gateway.example:2201,relay@10.0.0.8:22");
        assert_eq!(args.last().map(String::as_str), Some("admin@10.0.0.5"));
    }

    #[test]
    fn local_and_reverse_forwards_are_passed_as_separate_argv_values() {
        let mut config = cfg();
        config.forwards = vec![
            super::super::PortForward::Local {
                bind: "127.0.0.1:15432".into(),
                destination: "db.internal:5432".into(),
            },
            super::super::PortForward::Remote {
                bind: "127.0.0.1:18080".into(),
                destination: "127.0.0.1:8080".into(),
            },
        ];
        let args = argv(&build_command(&config, None));
        assert!(args.contains(&"ExitOnForwardFailure=yes".to_string()));
        assert!(args.windows(2).any(|w| w[0] == "-L" && w[1] == "127.0.0.1:15432:db.internal:5432"));
        assert!(args.windows(2).any(|w| w[0] == "-R" && w[1] == "127.0.0.1:18080:127.0.0.1:8080"));
    }

    #[test]
    fn proxyjump_brackets_ipv6_hosts() {
        let hop = super::super::JumpHost {
            user: "admin".into(),
            host: "2001:db8::1".into(),
            port: 2222,
        };
        assert_eq!(hop.proxy_spec(), "admin@[2001:db8::1]:2222");
    }

    #[test]
    fn pty_size_is_forwarded_unchanged() {
        let size = raw_size(PtySize { cols: 132, rows: 43 });
        assert_eq!((size.cols, size.rows), (132, 43));
    }

    /// Manual diagnostic for the ConPTY -> reader thread path. Ignored by
    /// default: CreatePseudoConsole needs an attached interactive console, and
    /// a headless `cargo test` process does not drive the child at all.
    #[cfg(windows)]
    #[test]
    #[ignore = "requires an attached interactive console"]
    fn conpty_forwards_child_output() {
        use portable_pty::PtySize as RawSize;
        use std::io::Read;
        use std::time::Duration;

        let pty = native_pty_system();
        let pair = pty
            .openpty(RawSize { rows: 24, cols: 80, pixel_width: 0, pixel_height: 0 })
            .unwrap();
        let marker = std::env::temp_dir().join(format!("sshterm-pty-{}.txt", std::process::id()));
        let marker_arg = format!("echo MARKER > {} & echo SSHtermConPtyOk", marker.display());
        let mut cmd = CommandBuilder::new("cmd.exe");
        cmd.arg("/c");
        cmd.arg(marker_arg);
        let mut child = pair.slave.spawn_command(cmd).unwrap();
        // Some ConPTY builds need an explicit resize before they flush output.
        let _ = pair.master.resize(RawSize {
            rows: 24,
            cols: 80,
            pixel_width: 0,
            pixel_height: 0,
        });
        let mut reader = pair.master.try_clone_reader().unwrap();

        let (tx, rx) = std::sync::mpsc::channel();
        std::thread::spawn(move || {
            let mut buf = [0u8; 4096];
            let mut all = Vec::new();
            for _ in 0..8 {
                match reader.read(&mut buf) {
                    Ok(0) | Err(_) => break,
                    Ok(n) => {
                        all.extend_from_slice(&buf[..n]);
                        if all.contains(&b'\n') && all.len() > 20 {
                            break;
                        }
                    }
                }
            }
            let _ = tx.send(all);
        });

        let got = rx.recv_timeout(Duration::from_secs(10));
        let ran = marker.exists();
        let status = child.try_wait();
        eprintln!("child ran (marker file) = {ran}, status = {status:?}");
        if ran {
            let _ = std::fs::remove_file(&marker);
        }
        let bytes = got.unwrap_or_else(|_| {
            panic!("no PTY output (child ran = {ran}, status = {status:?})")
        });
        let text = String::from_utf8_lossy(&bytes);
        eprintln!("ConPTY output: {text:?}");
        assert!(text.contains("SSHtermConPtyOk"), "PTY output was not forwarded");
        let _ = child.kill();
    }
}
